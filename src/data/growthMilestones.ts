// Helper to calculate days after sowing
export function calculateDAS(plantingDateStr: string): number {
  const planting = new Date(plantingDateStr);
  const now = new Date();
  // Strip time part
  const diffTime = now.getTime() - planting.getTime();
  const diffDays = Math.floor(diffTime / (1000 * 60 * 60 * 24));
  return Math.max(0, diffDays);
}

// Helper to format date offset
export function addDaysToDate(baseDateStr: string, days: number): string {
  const base = new Date(baseDateStr);
  base.setDate(base.getDate() + days);
  return base.toISOString().split('T')[0];
}

// Helper to format user-friendly display date
export function formatFriendlyDate(dateStr: string, language: 'en' | 'kn'): string {
  try {
    const d = new Date(dateStr);
    if (isNaN(d.getTime())) return dateStr;
    const options: Intl.DateTimeFormatOptions = { 
      year: 'numeric', 
      month: 'short', 
      day: 'numeric' 
    };
    return d.toLocaleDateString(language === 'kn' ? 'kn-IN' : 'en-IN', options);
  } catch (e) {
    return dateStr;
  }
}
